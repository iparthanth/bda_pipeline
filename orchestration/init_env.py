"""Create ``.env`` (git-ignored) with a random salt and random role tokens if it does not exist yet.

The salt (PRV-1) and the dashboard tokens (PRV-3) must never be committed; ``.env.example`` documents
the variables without values. Existing values are kept, so re-running is safe.
"""
from __future__ import annotations

import secrets

import yaml

from pipeline.common.config import REPO_ROOT


def main() -> None:
    env = REPO_ROOT / ".env"
    existing = {}
    if env.exists():
        for line in env.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                existing[k.strip()] = v.strip()
    wanted = {"EPISCOPE_SALT": secrets.token_hex(32)}
    roles = yaml.safe_load(open(REPO_ROOT / "config" / "roles.yaml"))["roles"]
    for r in roles.values():
        wanted[r["token_env"]] = secrets.token_urlsafe(24)
    added = [k for k in wanted if not existing.get(k)]
    if added:
        with open(env, "a") as fh:
            if not existing:
                fh.write("# Local secrets - generated by `make env`; never commit this file.\n")
            for k in added:
                fh.write(f"{k}={wanted[k]}\n")
    print(f".env ready ({'added ' + ', '.join(added) if added else 'unchanged'})")


if __name__ == "__main__":
    main()
